import type { BorrowSlip, BorrowSlipStatus } from '@/ticketing/types';

export function toDateInput(value: string | null | undefined): string {
  if (!value) return '';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '';
  return date.toISOString().slice(0, 10);
}

export function formatDateOnly(value: string | null | undefined): string {
  if (!value) return '—';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '—';
  return new Intl.DateTimeFormat('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
  }).format(date);
}

export function formatDateTime(value: string | null | undefined): string {
  if (!value) return '—';
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '—';
  return new Intl.DateTimeFormat('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
  }).format(date);
}

export function effectiveBorrowStatus(slip: BorrowSlip, now: Date = new Date()): BorrowSlipStatus {
  if (slip.status === 'returned') return 'returned';
  const expected = new Date(slip.expectedReturnDate).getTime();
  if (!Number.isNaN(expected) && expected < now.getTime()) return 'overdue';
  return slip.status;
}
